#!/usr/bin/env node
// Sets up the UniMisk CI for a NEW project from this repository (the toolkit): copies the universal pieces into the
// project, generates the parts that depend on its stack, and prints exactly what the admin must still do on the server.
//   node ci/bootstrap/new-project.mjs --id acme --repo UniMisk-Erp-Solutions/Acme --target ../Acme [--display "Acme"] [--write] [--baseline]
// Without --write it only prints the plan. Nothing here touches the server, GitHub or Jenkins.
//
// What is copied unchanged (universal):   ci/lib, ci/gate, ci/verify/quality (engine), ci/pipeline/{run-stage,scan-credentials}.mjs
// What is generated (project specific):   ci/pipeline/config.mjs (its build/test commands), Jenkinsfile, ci/verify/quality/policy.json,
//                                         ci/pipeline/overlay.mjs and run-trivy.mjs (its package folders)
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { parseRegistry } from "../gate-service/projects.mjs";
import { initPolicy } from "../verify/quality/run.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const TOOLKIT = path.resolve(HERE, "..", "..");
const SKIP = new Set(["node_modules", ".git", ".ci", "dist", "build", "ci"]);
const QUALITY = [["repo-policy", "Repository policy", "repo-policy"], ["code-standards", "Code standards", "standards"], ["maintainability", "Maintainability", "maintainability"], ["architecture", "Architecture", "architecture"]];

/** package.json folders (depth <= 2) and which of the standard scripts each defines. */
export function detectPackages(target) {
  const out = [];
  const scan = (rel, depth) => {
    const abs = path.join(target, rel);
    const pj = path.join(abs, "package.json");
    if (fs.existsSync(pj)) {
      let scripts = {}; try { scripts = JSON.parse(fs.readFileSync(pj, "utf8")).scripts || {}; } catch { /* unreadable package.json: no scripts */ }
      out.push({ dir: rel || ".", scripts: Object.keys(scripts), eslint: fs.existsSync(path.join(abs, "eslint.config.js")), tsci: fs.existsSync(path.join(abs, "tsconfig.ci.json")) });
    }
    if (depth >= 2) return;
    for (const d of fs.readdirSync(abs, { withFileTypes: true })) if (d.isDirectory() && !SKIP.has(d.name)) scan(rel ? `${rel}/${d.name}` : d.name, depth + 1);
  };
  scan("", 0);
  return out;
}

const npmRun = (pkg, script) => ({ cmd: "npm", args: pkg === "." ? ["run", script] : ["--prefix", pkg, "run", script] });

export function buildStages(packages) {
  const stages = {};
  const withScript = (s) => packages.filter((p) => p.scripts.includes(s));
  const add = (name, phase, title, scripts, env) => { const ps = withScript(scripts); if (ps.length) stages[name] = { phase, title, commands: ps.map((p) => ({ ...npmRun(p.dir, scripts), ...(env ? { env } : {}) })) }; };
  add("lint", "build", "ESLint", "lint");
  add("typecheck", "build", "TypeScript check", "typecheck");
  add("build", "build", "Production build", "build", "CI_BUILD_ENV");
  add("unit-tests", "test", "Unit tests", "test", "CI_BUILD_ENV");
  stages["trivy-deps"] = { phase: "test", title: "Trivy dependency scan", commands: [{ cmd: "node", args: ["ci/pipeline/run-trivy.mjs", "deps"] }] };
  stages["trivy-secrets"] = { phase: "test", title: "Trivy + pattern secret scan", commands: [{ cmd: "node", args: ["ci/pipeline/run-trivy.mjs", "secrets"] }, { cmd: "node", args: ["ci/pipeline/scan-credentials.mjs"] }] };
  for (const [name, title, check] of QUALITY) stages[name === "code-standards" ? "code-standards" : name] = { phase: "build", title, commands: [{ cmd: "node", args: ["ci/verify/quality/run.mjs", check] }] };
  return stages;
}

const js = (v) => JSON.stringify(v);
export function renderConfig(stages, display) {
  const body = Object.entries(stages).map(([name, s]) => `  ${/^[a-z]+$/.test(name) ? name : js(name)}: {\n    phase: ${js(s.phase)}, title: ${js(s.title)},\n    commands: [${s.commands.map((c) => `{ cmd: ${js(c.cmd)}, args: ${js(c.args)}${c.env ? `, env: ${c.env}` : ""} }`).join(", ")}],\n  },`).join("\n");
  return `// Single source of truth for the ${display} CI pipeline (generated by ci/bootstrap/new-project.mjs, then owned by this project).
// The Jenkinsfile, the stage runner, the pre-PR gate and the tests all read this file. Review it: it lists what "verified" means here.
import path from "node:path";
import { fileURLToPath } from "node:url";

export const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
export const RESULTS_DIR = path.join(REPO_ROOT, ".ci", "results");

/** Hosts that must NEVER be reachable from, or baked into, CI builds (production API, production database ...). Fill these in. */
export const PRODUCTION_HOSTS = [];

/** Inert values used for every CI build and test run. Use values that can never reach production (".invalid" never resolves). */
export const CI_BUILD_ENV = {};

/** Stage name -> how to run it. A stage is PASS only when every command exits 0. */
export const STAGES = {
${body}
};

/** Every one of these must be PASS before an attestation is issued. */
export const REQUIRED_CHECKS = Object.keys(STAGES);

export const GITHUB_CHECK_NAME = "unimisk/verified";
`;
}

export function renderJenkinsfile(stages, packages, display, repo) {
  const has = (n) => Boolean(stages[n]);
  const run = (n) => `sh 'node ci/pipeline/run-stage.mjs ${n}'`;
  const group = (title, names, titles) => `    stage('${title}') {\n      parallel {\n${names.filter(has).map((n) => `        stage('${titles[n]}') { steps { ${run(n)} } }`).join("\n")}\n      }\n    }\n`;
  const installs = packages.map((p) => `        sh 'npm ${p.dir === "." ? "" : `--prefix ${p.dir} `}install --no-audit --no-fund'`).join("\n");
  const buildStage = has("build") ? `    stage('Build') {\n      steps { ${run("build")} }\n    }\n\n` : "";
  return `// ${display} CI. Triggered by a push to GitHub (gate -> Jenkins branch scan); see the platform docs (docs/ci-cd-pipeline.md).
//   push -> checks -> (gate verifies independently, signs, publishes the commit status) -> PR review -> ADMIN merge
// This file ONLY builds and tests. It runs on the "untrusted" agent, a container with no secrets: it holds no signing key,
// no GitHub token, and cannot reach the gate. It NEVER merges, pushes or deploys.
// Changing this file or the pipeline scripts under ci/ makes the gate refuse to sign until an admin approves the change.
pipeline {
  agent { label 'untrusted' }

  options {
    timestamps()
    timeout(time: 45, unit: 'MINUTES')
    disableConcurrentBuilds(abortPrevious: true)
    buildDiscarder(logRotator(numToKeepStr: '10', daysToKeepStr: '14'))
  }

  environment {
    CI_REPO           = '${repo}'
    NPM_CONFIG_AUDIT  = 'false'
    NPM_CONFIG_FUND   = 'false'
  }

  stages {
    // CENTRAL PIPELINE: the CI-owned files (ci/, lint/type config) are always taken from the trusted ref, never from the branch.
    stage('Trusted pipeline') {
      steps {
        script {
          def ref = env.CI_TOOLKIT_REF ?: 'main'
          dir('.ci-toolkit') { git url: 'https://github.com/' + env.CI_REPO + '.git', branch: ref, changelog: false, poll: false }
        }
        sh 'node .ci-toolkit/ci/pipeline/overlay.mjs --toolkit .ci-toolkit --workspace .'
        sh 'rm -rf .ci-toolkit'
      }
    }

    stage('Install') {
      steps {
        sh 'node --version && npm --version && trivy --version | head -1'
${installs}
      }
    }

    // Engineering quality (UniMisk standard): fast static gates that block only NEW or WORSENED problems against the baseline.
${group("Engineering quality", ["repo-policy", "code-standards", "maintainability", "architecture"], { "repo-policy": "Repository policy", "code-standards": "Code standards", maintainability: "Maintainability", architecture: "Architecture" })}
    stage('Checks') {
      parallel {
${["lint", "typecheck", "trivy-secrets"].filter(has).map((n) => `        stage('${{ lint: "Lint", typecheck: "Typecheck", "trivy-secrets": "Secrets" }[n]}') { steps { ${run(n)} } }`).join("\n")}
      }
    }

${buildStage}    stage('Test') {
      parallel {
${["unit-tests", "trivy-deps"].filter(has).map((n) => `        stage('${{ "unit-tests": "Unit tests", "trivy-deps": "Dependencies" }[n]}') { steps { ${run(n)} } }`).join("\n")}
      }
    }
  }

  post {
    always {
      archiveArtifacts artifacts: '.ci/results/*.json, .ci/toolkit.json, .ci/quality/*.json', allowEmptyArchive: true
    }
    cleanup { cleanWs(deleteDirs: true, notFailBuild: true) }
  }
}
`;
}

/** Replaces `a` by `b` in a copied toolkit file; a toolkit change that removes the anchor must fail loudly, not silently skip. */
function patch(text, a, b, label) { if (!text.includes(a)) throw new Error(`bootstrap anchor missing in ${label}: the toolkit changed, update ci/bootstrap/new-project.mjs`); return text.replace(a, () => b); }

export function planProject({ id, repo, display, target, toolkit = TOOLKIT }) {
  const reg = parseRegistry({ defaultProject: id, projects: [{ id, repo, jenkinsFolder: id, displayName: display }] }); // validates id and repo
  const packages = detectPackages(target);
  if (!packages.length) throw new Error("no package.json found in the target (depth 2): nothing to build or test");
  const stages = buildStages(packages);
  const files = new Map();
  const copy = (rel) => { const abs = path.join(toolkit, rel); if (fs.statSync(abs).isDirectory()) { for (const n of fs.readdirSync(abs)) copy(`${rel}/${n}`); } else files.set(rel, fs.readFileSync(abs, "utf8")); };
  for (const rel of ["ci/lib", "ci/gate", "ci/pipeline/run-stage.mjs", "ci/pipeline/scan-credentials.mjs", "ci/verify/quality/run.mjs", "ci/verify/quality/lib"]) copy(rel);
  // overlay: which CI-owned files replace the branch's own (a branch must not weaken its lint or type config)
  const owned = ["ci", ".trivyignore", ...packages.flatMap((p) => [p.eslint ? `${p.dir === "." ? "" : p.dir + "/"}eslint.config.js` : null, p.tsci ? `${p.dir === "." ? "" : p.dir + "/"}tsconfig.ci.json` : null].filter(Boolean))];
  let overlay = fs.readFileSync(path.join(toolkit, "ci/pipeline/overlay.mjs"), "utf8");
  overlay = patch(overlay, `  "ci",\n  "frontend/eslint.config.js", "frontend/tsconfig.ci.json", "frontend/playwright.config.js", "frontend/e2e",\n  "backend/eslint.config.js", ".trivyignore",\n`, `  ${owned.map(js).join(", ")},\n`, "overlay OVERLAY_PATHS");
  overlay = patch(overlay, `const PACKAGES = ["frontend", "backend"];`, `const PACKAGES = ${js(packages.map((p) => p.dir))};`, "overlay PACKAGES");
  files.set("ci/pipeline/overlay.mjs", overlay);
  let trivy = fs.readFileSync(path.join(toolkit, "ci/pipeline/run-trivy.mjs"), "utf8");
  trivy = patch(trivy, `for (const dir of ["frontend", "backend"]) {`, `for (const dir of ${js(packages.map((p) => p.dir))}) {`, "run-trivy dirs");
  files.set("ci/pipeline/run-trivy.mjs", trivy);
  files.set("ci/pipeline/config.mjs", renderConfig(stages, display));
  files.set("Jenkinsfile", renderJenkinsfile(stages, packages, display, repo));
  files.set("ci/verify/quality/policy.json", JSON.stringify(initPolicy(target, display), null, 2) + "\n");
  const registryEntry = { id, displayName: display, repo, jenkinsFolder: id, requiredChecks: Object.keys(stages), developers: [] };
  return { reg, packages, stages, files, registryEntry };
}

function main() {
  const a = process.argv.slice(2);
  const opt = (k) => (a.includes(`--${k}`) ? a[a.indexOf(`--${k}`) + 1] : undefined);
  const id = opt("id"), repo = opt("repo"), t = opt("target");
  if (!id || !repo || !t) { console.error('usage: node ci/bootstrap/new-project.mjs --id acme --repo Org/Acme --target ../Acme [--display "Acme"] [--write] [--baseline]'); process.exit(2); }
  const target = path.resolve(t);
  let plan;
  try { plan = planProject({ id, repo, display: opt("display") || id, target }); } catch (e) { console.error(`✘ ${e.message}`); process.exit(1); }
  console.log(`Project "${id}" (${repo}) at ${target}`);
  console.log(`  packages found: ${plan.packages.map((p) => `${p.dir} [${p.scripts.filter((s) => ["lint", "typecheck", "build", "test"].includes(s)).join(", ") || "no standard scripts"}]`).join("; ")}`);
  console.log(`  required checks: ${Object.keys(plan.stages).join(", ")}`);
  console.log(`  files to write (${plan.files.size}): ${[...plan.files.keys()].filter((f) => !f.startsWith("ci/lib/") && !f.startsWith("ci/gate/") && !f.includes("quality/lib/")).join(", ")} + the shared ci/lib, ci/gate and the quality engine`);
  if (a.includes("--write")) {
    for (const [rel, text] of plan.files) { const f = path.join(target, rel); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, text); }
    console.log("✔ written");
    if (a.includes("--baseline")) {
      const r = spawnSync(process.execPath, ["ci/verify/quality/run.mjs", "all", "--update-baseline"], { cwd: target, encoding: "utf8" });
      console.log(r.status === 0 ? "✔ quality baseline recorded from the current code (review it: it is the debt that may not grow)" : `! baseline not recorded (install the project's dependencies first, then run: node ci/verify/quality/run.mjs all --update-baseline): ${(r.stderr || r.stdout || "").split("\n")[0]}`);
    }
  } else console.log("(dry run: add --write to create the files)");
  console.log(`
Still to do (admin):
  1. In the project: open ci/pipeline/config.mjs and fill PRODUCTION_HOSTS and CI_BUILD_ENV; open ci/verify/quality/policy.json and write the architecture rules with the team.
  2. Run  node ci/verify/quality/run.mjs all --audit  then  --update-baseline  (or re-run this tool with --baseline). Commit everything in a pull request; an admin reviews and merges it.
  3. Add this entry to ci/projects.json in the platform repository (fill developers) and run  node ci/jenkins/generate.mjs :
${JSON.stringify(plan.registryEntry, null, 2).split("\n").map((l) => "       " + l).join("\n")}
  4. On the CI server: create secrets/projects/${id}/webhook-secret (a random string), copy ${id}'s Jenkinsfile to ci/jenkins/casc/projects/${id}/Jenkinsfile,
     rebuild and restart Jenkins and the gate (docs/ci-cd-pipeline.md, "Adding a project").
  5. Optional: add a GitHub webhook to  <gate address>/github/${id}  with that secret (the gate also detects pushes by itself).`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) main();
